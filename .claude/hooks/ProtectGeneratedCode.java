/**
 * PreToolUse hook: blocks edits to build output and generated code.
 *
 * <p>Everything under {@code target/} is rebuilt by Maven, and the SBE and Protobuf codecs are
 * generated from the schemas in {@code contracts/}. An edit there is lost on the next build, so it
 * is blocked (exit code 2) with a message pointing to the source to change instead.
 */
public final class ProtectGeneratedCode {

  public static void main(String[] args) throws Exception {
    HookInput input = HookInput.fromStdin();
    String path =
        HookInput.normalize(
            input.string("file_path").or(() -> input.string("notebook_path")).orElse(""));
    if (!isGenerated(path)) {
      return;
    }
    System.err.println("Blocked: " + path + " is generated by the build and must not be edited.");
    if (path.contains("/generated-sources/sbe/")) {
      System.err.println(
          "Change the SBE schema instead: contracts/src/main/resources/sbe/argus-fastpath.xml");
    } else if (path.contains("/generated-sources/protobuf/")) {
      System.err.println("Change the Protobuf schemas instead: contracts/src/main/protobuf/");
    } else {
      System.err.println("Change the sources it is built from, then run ./mvnw verify.");
    }
    System.err.println("See contracts/README.md for how the schemas evolve.");
    System.exit(2);
  }

  static boolean isGenerated(String path) {
    return path.contains("/target/") || path.contains("/generated-sources/");
  }
}
