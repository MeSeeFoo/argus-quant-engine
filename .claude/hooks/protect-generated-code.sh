#!/usr/bin/env bash
# PreToolUse hook: blocks edits to build output and generated code.
#
# Everything under target/ is rebuilt by Maven, and the SBE and Protobuf codecs
# are generated from the schemas in contracts/. An edit there is lost on the
# next build, so it is blocked (exit code 2) with the source to change instead.
set -eu
# shellcheck source=lib.sh
. "$(dirname "$0")/lib.sh"

path=$(json_string file_path)
[ -n "$path" ] || path=$(json_string notebook_path)
is_generated "$path" || exit 0

path=${path//\\//}
{
  echo "Blocked: $path is generated by the build and must not be edited."
  case $path in
    */generated-sources/sbe/*)
      echo "Change the SBE schema instead: contracts/src/main/resources/sbe/argus-fastpath.xml" ;;
    */generated-sources/protobuf/*)
      echo "Change the Protobuf schemas instead: contracts/src/main/protobuf/" ;;
    *)
      echo "Change the sources it is built from, then run ./mvnw verify." ;;
  esac
  echo "See contracts/README.md for how the schemas evolve."
} >&2
exit 2
